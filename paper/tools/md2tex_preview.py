"""Minimal JOSS-paper Markdown -> LaTeX converter for a local preview PDF."""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
text = src.read_text()
_, yaml, body = text.split("---", 2)
title = re.search(r"title: '(.*)'", yaml).group(1)
author = re.search(r"- name: (.*)", yaml).group(1)
orcid = re.search(r"orcid: (.*)", yaml).group(1).strip()
aff = re.search(r"affiliations:\s*\n\s*- name: (.*)", yaml).group(1)
date = re.search(r"date: (.*)", yaml).group(1)

def esc(s):
    return (s.replace("\\", "\x00").replace("&", r"\&").replace("%", r"\%")
             .replace("#", r"\#").replace("_", r"\_").replace("~", r"\textasciitilde{}")
             .replace("^", r"\^{}").replace("\x00", "\\"))

def inline(s):
    parts = re.split(r"(\$[^$]+\$|`[^`]+`|\\autoref\{[^}]+\}|\\label\{[^}]+\})", s)
    res = []
    for p in parts:
        if p.startswith("$") or p.startswith("\\autoref") or p.startswith("\\label"):
            res.append(p)
        elif p.startswith("`"):
            res.append(r"\texttt{" + esc(p[1:-1]).replace("{\\textasciitilde{}}", "~") + "}")
        else:
            p = esc(p)
            p = re.sub(r"\[@([\w:-]+)\]", r"\\parencite{\1}", p)
            p = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", p)
            p = re.sub(r"(?<!\w)\*(?!\s)(.+?)\*(?!\w)", r"\\emph{\1}", p)
            res.append(p)
    return "".join(res)

blocks = re.split(r"\n\s*\n", body.strip())
tex = []; i = 0
while i < len(blocks):
    b = blocks[i].strip()
    if b.startswith("# References"):
        tex.append(r"\printbibliography[heading=bibintoc,title=References]")
    elif b.startswith("### "):
        tex.append(r"\subsection*{" + inline(b[4:]) + "}")
    elif b.startswith("# "):
        tex.append(r"\section*{" + inline(b[2:]) + "}")
    elif b.startswith("!["):
        m = re.match(r"!\[(.*)\]\((.*?)\)(\{ width=(\d+)% \})?", b, re.S)
        cap, path, _, w = m.groups()
        w = int(w) / 100 if w else 1.0
        tex.append("\\begin{figure}[htbp]\\centering\n\\includegraphics[width=%.2f\\linewidth]{%s}\n\\caption{%s}\n\\end{figure}"
                   % (w, path, inline(" ".join(cap.split()))))
    elif b.startswith(": "):
        cap = inline(b[2:]); tbl = blocks[i + 1].strip().splitlines(); i += 1
        rows = [[c.strip() for c in r.strip("|").split("|")] for r in tbl if not re.match(r"^\|[:\- |]+\|$", r)]
        spec = "l" + "r" * (len(rows[0]) - 1)
        lines = [r"\begin{table}[htbp]\centering\small", r"\caption{%s}" % cap,
                 r"\begin{tabular}{%s}\toprule" % spec,
                 " & ".join(r"\textbf{%s}" % inline(c) for c in rows[0]) + r" \\\midrule"]
        lines += [" & ".join(inline(c) for c in r) + r" \\" for r in rows[1:]]
        lines += [r"\bottomrule\end{tabular}", r"\end{table}"]
        tex.append("\n".join(lines))
    elif re.match(r"^(\*|\d+\.) ", b):
        env = "itemize" if b.startswith("*") else "enumerate"
        items = re.split(r"\n(?=\* |\d+\. )", b)
        tex.append("\\begin{%s}\n" % env + "\n".join(
            r"\item " + inline(" ".join(re.sub(r"^(\*|\d+\.) ", "", it).split())) for it in items)
            + "\n\\end{%s}" % env)
    else:
        tex.append(inline(" ".join(b.split())))
    i += 1

doc = r"""\documentclass[10pt,a4paper]{article}
\usepackage[margin=2.2cm]{geometry}
\usepackage{fontspec}\setmainfont{Helvetica Neue}\setmonofont{Menlo}[Scale=0.85]
\usepackage{graphicx,booktabs,xcolor,amsmath}
\usepackage[style=authoryear,maxcitenames=2,uniquelist=false,backend=biber]{biblatex}
\addbibresource{paper.bib}
\definecolor{joss}{HTML}{8B1A1A}
\usepackage[colorlinks=true,linkcolor=joss,citecolor=joss,urlcolor=joss]{hyperref}
\usepackage{titlesec}
\titleformat*{\section}{\large\bfseries\color{joss}}
\titleformat*{\subsection}{\normalsize\bfseries}
\setlength{\parskip}{0.5em}\setlength{\parindent}{0pt}
\renewcommand{\figureautorefname}{Figure}\renewcommand{\tableautorefname}{Table}
\begin{document}
{\noindent\fbox{\parbox{\linewidth}{\footnotesize\textbf{Local preview} --- formatted to resemble a JOSS paper; the official PDF is generated by JOSS on submission.}}}
\vspace{1em}

{\Large\bfseries %s\par}
\vspace{0.8em}
{\normalsize %s\textsuperscript{1} \href{https://orcid.org/%s}{(ORCID %s)}\par}
{\small\textsuperscript{1} %s\par}
{\small %s\par}
\vspace{1em}
%s
\end{document}
""" % (inline(title), author, orcid, orcid, inline(aff), date, "\n\n".join(tex))
out.write_text(doc)
