"""Build the "Projectile Motion" demo .ksheet example.

A worked physics example showing every rich feature the authoring
library supports: a title block, a styled/banded data table driven by
formulas, designated X/Y columns, a summary panel with conditional
accent fills, yellow sticky notes, an embedded trajectory chart and a
LaTeX equation.

Run:  python examples/build_projectile_motion.py

Copyright (C) 2026 Gwilherm Kerherve — GPL-3.0-or-later.
"""

import os

import numpy as np

from ksheet_author import Workbook, Series, PALETTE


def build() -> str:
    g = 9.81          # gravity (m/s^2)
    v0 = 30.0         # launch speed (m/s)
    angle = 45.0      # launch angle (deg)

    wb = Workbook(min_rows=44, min_cols=14)
    s = wb.add_sheet("Projectile")

    # --- Title -------------------------------------------------------
    s.title_block("Projectile Motion",
                  "Trajectory of a launched body under gravity "
                  "(no air resistance)")

    # --- Input panel (editable parameters) ---------------------------
    inputs = [("Launch speed v₀ (m/s)", v0),
              ("Launch angle θ (°)", angle),
              ("Gravity g (m/s²)", g)]
    s.set(3, 0, "Inputs")
    s.fmt(3, 0, bold=True, font_color=PALETTE["accent"])
    for i, (lbl, val) in enumerate(inputs):
        r = 4 + i
        s.set(r, 0, lbl)
        s.set(r, 1, val)
        s.fmt(r, 1, bg=PALETTE["warn"], align="center", number_format="0.00")
    s.box(4, 0, 6, 1, color=PALETTE["accent"], width=1.0)
    s.col_width(0, 200)
    s.note(4, 1, "Edit any input — the table, summary, chart and "
                 "formulas all recompute on open.", kind="note")

    # Derived launch components (named via positions B5=v0, B6=angle).
    s.set(3, 3, "Derived")
    s.fmt(3, 3, bold=True, font_color=PALETTE["accent"])
    s.set(4, 3, "vx = v₀ cosθ")
    s.formula(4, 4, "=B5*COS(RADIANS(B6))")
    s.set(5, 3, "vy = v₀ sinθ")
    s.formula(5, 4, "=B5*SIN(RADIANS(B6))")
    s.set(6, 3, "Flight time T")
    s.formula(6, 4, "=2*E6/B7")
    s.fmt_range(4, 4, 6, 4, align="center", number_format="0.00",
                bg=PALETTE["band"])
    s.col_width(3, 130)

    # --- Data table: time / x / y -----------------------------------
    n = 21
    T = 2 * v0 * np.sin(np.radians(angle)) / g
    times = np.linspace(0, T, n)
    table_start = 9
    rows = []
    for k, t in enumerate(times):
        # 1-based sheet row of this data row: header sits at sheet row
        # (table_start+1), so the first data row is (table_start+2).
        rr = table_start + 2 + k
        rows.append([
            round(float(t), 3),
            f"=$E$5*A{rr}",                       # x = vx * t
            f"=$E$6*A{rr}-0.5*$B$7*A{rr}*A{rr}",  # y = vy*t - 0.5 g t^2
        ])
    s.set(8, 0, "Trajectory samples")
    s.fmt(8, 0, bold=True, font_color=PALETTE["header"])
    s.table(table_start, 0,
            headers=["t (s)", "x (m)", "y (m)"],
            rows=rows, number_format="0.00")
    # Designate columns so the app knows the axes.
    s.designate(0, "X")
    s.designate(1, "Y")
    s.designate(2, "Y")

    # --- Summary panel ----------------------------------------------
    first = table_start + 2          # 1-based row of first data row
    last = table_start + 1 + n       # 1-based row of last data row
    s.set(8, 5, "Summary")
    s.fmt(8, 5, bold=True, font_color=PALETTE["header"])
    summ = [
        ("Max height (m)", f"=MAX(C{first}:C{last})", PALETTE["good"]),
        ("Range (m)", f"=MAX(B{first}:B{last})", PALETTE["band"]),
        ("Flight time (s)", "=E7", PALETTE["band"]),
    ]
    for i, (lbl, expr, col) in enumerate(summ):
        r = 9 + i
        s.set(r, 5, lbl)
        s.formula(r, 6, expr)
        s.fmt(r, 5, align="left")
        s.fmt(r, 6, bg=col, align="center", number_format="0.00", bold=True)
    s.box(9, 5, 11, 6, color=PALETTE["header"], width=1.0)
    s.col_width(5, 150)

    # --- Chart -------------------------------------------------------
    x = v0 * np.cos(np.radians(angle)) * times
    y = (v0 * np.sin(np.radians(angle)) * times - 0.5 * g * times ** 2)
    s.chart(
        [Series(x, y, "Trajectory", "Line+Symbol", color="#4472c4",
                linewidth=2.0, marker="o", markersize=4.0)],
        at=(560, 30), size=(440, 300),
        title="Projectile trajectory", xlabel="x (m)", ylabel="height (m)",
        grid=True, legend=True)

    # --- Equation ----------------------------------------------------
    s.equation(r"y(t) = v_0 \sin\theta \; t - \tfrac{1}{2} g t^2",
               at=(560, 350), fontsize=18, color="#222222",
               bg_color="#ffffff", border_color=PALETTE["header"],
               border_width=1.2)
    s.note(0, 8, "This whole sheet was generated by the "
                 "ksheet-example-author agent.", kind="note")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "Projectile Motion.ksheet")
    wb.save(out)
    return out


if __name__ == "__main__":
    print("Wrote", build())
